#ifndef _MPC_REFERENCE_HPP_
#define _MPC_REFERENCE_HPP_

#include "motion/pathing/arclengthSplining.hpp"
#include "config/constants.h"
#include "localization/odometry.hpp"
#define EIGEN_STACK_ALLOCATION_LIMIT 1048576
#include <Eigen/Dense>
#include <cstddef>

//builds the MPC reference trajectory: F+1 target poses (x, y, theta) rolled out along an ALS path
//headings use the Pose convention (0 along +y, pi/2 along +x), the same as ALS_Path headings
template<std::size_t F>
class MPCReference {
    public:
        //timing, drivetrain, and reference-gen limits (defaults from config/constants.h)
        struct Params {
            double h = MPC_SAMPLE_PERIOD; //sample period (s)
            double r = DRIVE_WHEEL_DIAMETER_INCHES / 2.0; //wheel radius (in)
            double track_width = TRACK_WIDTH; //track width (in)
            double a = MPC_MOTOR_A; //motor time-constant
            double b = MPC_MOTOR_B; //motor gain constant
            double a_max = MPC_A_MAX; //max accel of bot (in/s^2)
            double v_ref_min = MPC_V_REF_MIN; //speed floor (in/s)
        };

        static constexpr std::size_t r_states = 3; //x, y, theta per stage
        using ZRef = Eigen::Matrix<double, r_states * (F + 1), 1>;

        explicit MPCReference(const Params& params);

        //forget last cycle's reference speed (call on new path)
        void reset() {
            m_v_ref = -1.0;
        }

        //roll out F+1 reference poses from the closest sample idx (idx must be a valid sample index)
        /* the reference is generated by looking forward along the path, where
        speed is limited by curvature, by a lookahead braking constraint and
        by an accel/decel limit, and forced to zero at the path end.
        headings are rate-limited so the ref never asks for an infeasible turn rate */
        //omega_L, omega_R: measured wheel speeds (rad/s)
        ZRef build(const Pose& currentPose, const ALS_Path& path, std::size_t idx, bool reverse, double omega_L, double omega_R);

    private:
        Params m_params;
        //last cycle's 1st stage reference speed, seeds the next rollout (-1 = none yet)
        double m_v_ref = -1.0;
};

#endif
