#ifndef _MPC_REFERENCE_HPP_
#define _MPC_REFERENCE_HPP_

#include "motion/pathing/arclengthSplining.hpp"
#include "config/constants.h"
#include "localization/odometry.hpp"
#include "mpc/drivetrain.hpp"
#define EIGEN_STACK_ALLOCATION_LIMIT 1048576
#include <Eigen/Dense>
#include <array>
#include <cstddef>
#include <cstdint>

//how the reference heading is chosen along the path
enum class HeadingMode : uint8_t {
    TANGENT, //face along the path (backwards on a reverse path), the only mode a diff drive can follow
    HOLD //keep the heading the robot had on the first build after reset(), X and H drives only
};

//builds the MPC reference trajectory: F+1 target poses (x, y, theta) rolled out along an ALS path
//headings use the Pose convention (0 along +y, pi/2 along +x), the same as ALS_Path headings
template<class Drive, std::size_t F>
class MPCReference {
    public:
        static constexpr std::size_t N = Drive::N_GROUPS;
        using VecM = Eigen::Matrix<double, N, 1>;

        //timing, drivetrain, and reference-gen limits (the controller fills these from its own params)
        struct Params {
            double h = MPC_SAMPLE_PERIOD; //sample period (s)
            kinematics::DriveGeometry geom; //drivetrain geometry, read by Drive::G and Drive::K
            std::array<double, N> a{}; //motor time-constant per group
            std::array<double, N> b{}; //motor gain constant per group
            double a_max = MPC_A_MAX; //max accel of bot (in/s^2)
            double v_ref_min = MPC_V_REF_MIN; //speed floor (in/s)
            double a_lat_max = MPC_A_LAT_MAX; //cornering accel cap for X and H drives (in/s^2)
            HeadingMode heading = HeadingMode::TANGENT; //forced to TANGENT on a diff drive
        };

        static constexpr std::size_t r_states = 3; //x, y, theta per stage
        using ZRef = Eigen::Matrix<double, r_states * (F + 1), 1>;

        explicit MPCReference(const Params& params);

        //forget last cycle's reference speed and held heading (call on new path)
        void reset() {
            m_v_ref = -1.0;
            m_have_hold = false;
        }

        //roll out F+1 reference poses from the closest sample idx (idx must be a valid sample index)
        /* the reference is generated by looking forward along the path, where
        speed is limited by every group's top speed (with the turn the heading needs),
        by a cornering accel cap on X and H drives, by a lookahead braking constraint and
        by an accel/decel limit, and forced to zero at the path end.
        headings are rate-limited so the ref never asks for an infeasible turn rate */
        //omega: measured group speeds (rad/s)
        ZRef build(const Pose& currentPose, const ALS_Path& path, std::size_t idx, bool reverse, const VecM& omega);

    private:
        Params m_params;
        //group speeds from body twist, and body twist from group speeds (see mpc/drivetrain.hpp)
        kinematics::Mat<N, 3> m_G;
        kinematics::Mat<3, N> m_K;
        //last cycle's 1st stage reference speed, seeds the next rollout (-1 = none yet)
        double m_v_ref = -1.0;
        //heading HOLD keeps, latched on the first build after reset()
        double m_hold_theta = 0.0;
        bool m_have_hold = false;
};

#endif
